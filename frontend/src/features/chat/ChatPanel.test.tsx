import { afterEach, describe, expect, it, vi } from 'vitest';
import { cleanup, render, renderHook, screen } from '@testing-library/react';
import type { SystemHealth } from '../../data/contracts';

const health = vi.hoisted(() => ({ data: undefined as Partial<SystemHealth> | undefined }));
vi.mock('../../data/queries', () => ({ useHealth: () => ({ data: health.data }) }));

const { ChatNotice, chatNotice, useChatAvailability } = await import('./ChatPanel');

afterEach(() => { cleanup(); health.data = undefined; });

describe('chat notice (Gemini API terms)', () => {
  it('free tier: 18+, inputs may be read by reviewers, no personal information', () => {
    const { lead, rest } = chatNotice('free');
    expect(lead).toBe('18+ only.');
    expect(rest).toMatch(/free tier/);
    expect(rest).toMatch(/human reviewers may read it/);
    expect(rest).toMatch(/Don't enter personal information/);
  });

  it('paid tier: still 18+, no review warning', () => {
    const { lead, rest } = chatNotice('paid');
    expect(lead).toBe('18+ only.');
    expect(rest).not.toMatch(/free tier|reviewers/);
  });

  it('an unknown tier shows the stricter free-tier notice', () => {
    expect(chatNotice(undefined)).toEqual(chatNotice('free'));
    expect(chatNotice(null)).toEqual(chatNotice('free'));
  });

  it('renders the tier the server reports', () => {
    health.data = { backend: true, chat: { status: 'ready', tier: 'paid' } };
    render(<ChatNotice />);
    const note = screen.getByTestId('chat-notice');
    expect(note.textContent).toMatch(/^18\+ only\. Answers are generated by Google Gemini/);
  });
});

describe('useChatAvailability', () => {
  const state = (h: Partial<SystemHealth> | undefined) => {
    health.data = h;
    return renderHook(() => useChatAvailability()).result.current;
  };

  it('is unknown while health is loading', () => expect(state(undefined)).toEqual({ ready: null, message: null }));
  it('is ready only when the server says so', () => expect(state({ backend: true, chat: { status: 'ready' } }).ready).toBe(true));
  it('explains a switched-off chat', () => expect(state({ backend: true, chat: { status: 'offline' } }).message).toMatch(/switched off/));
  it('explains an unreachable server', () => expect(state({ backend: false }).message).toMatch(/not reachable/));
  it('never claims readiness for an unconfigured chat', () => expect(state({ backend: true, chat: { status: 'unconfigured' } }).ready).toBe(false));
});
